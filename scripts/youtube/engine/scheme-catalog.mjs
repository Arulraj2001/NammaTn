export function getSchemeById(id) {
  return TN_SCHEMES_CATALOG.find(s => s.id === id) || null;
}

export function getTodayScheme(dateStr = null) {
  const d = dateStr ? new Date(dateStr) : new Date();
  const dayOfYear = Math.floor((d - new Date(d.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
  const index = dayOfYear % TN_SCHEMES_CATALOG.length;
  return TN_SCHEMES_CATALOG[index];
}

