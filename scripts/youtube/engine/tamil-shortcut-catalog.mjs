export function getTamilShortcutForRun(recentlyUsedIds = new Set()) {
  const pool = TAMIL_SHORTCUT_CATALOG.filter(item => !recentlyUsedIds.has(item.id));
  const candidates = pool.length > 0 ? pool : TAMIL_SHORTCUT_CATALOG;
  const dayOfYear = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0)) / 86400000);
  return candidates[dayOfYear % candidates.length];
}
