export function getInfotainmentTopicById(id) {
  return INFOTAINMENT_CATALOG.find(t => t.id === id) || null;
}

/**
 * Returns the exact topic for the designated broadcast slot.
 * - Afternoon slot: Alternates between 'mega-projects' and 'consumer-scams'
 * - Evening slot: Cycles through 'untold-mysteries'
 * Guarantees zero duplicate content on the same day.
 */
export function getInfotainmentTopicForSlot(slot = 'infotainment-afternoon', dateStr = null) {
  const d = dateStr ? new Date(dateStr) : new Date();
  const dayOfYear = Math.floor((d - new Date(d.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));

  if (slot === 'infotainment-afternoon') {
    // Combine mega-projects & consumer-scams
    const afternoonPillars = INFOTAINMENT_CATALOG.filter(t => t.pillar === 'mega-projects' || t.pillar === 'consumer-scams');
    const index = dayOfYear % afternoonPillars.length;
    return afternoonPillars[index];
  }

  if (slot === 'infotainment-evening') {
    // Pure untold mysteries
    const eveningPillars = INFOTAINMENT_CATALOG.filter(t => t.pillar === 'untold-mysteries');
    const index = dayOfYear % eveningPillars.length;
    return eveningPillars[index];
  }

  const index = dayOfYear % INFOTAINMENT_CATALOG.length;
  return INFOTAINMENT_CATALOG[index];
}

