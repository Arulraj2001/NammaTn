/**
 * Breaks long sentences into punchy kinetic chunks
 * Shorts: 2 to 3 words (CapCut / Hormozi pop-up)
 * Long-form: 4 to 6 words (Vox broadcast style)
 */
export function chunkSentenceForCaptions(sentence, totalDurationSec, startTimeOffset = 0, wordsPerChunk = 3) {
  const tanglish = toTanglish(sentence);
  const cleanedSentence = cleanCaptionText(tanglish);
  const words = cleanedSentence.split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];

  const chunkCount = Math.ceil(words.length / wordsPerChunk);
  const durationPerChunk = totalDurationSec / chunkCount;

  const chunks = [];
  for (let i = 0; i < chunkCount; i++) {
    const chunkWords = words.slice(i * wordsPerChunk, (i + 1) * wordsPerChunk);
    const start = startTimeOffset + (i * durationPerChunk);
    const end = startTimeOffset + ((i + 1) * durationPerChunk);

    const chunkText = cleanCaptionText(chunkWords.join(' '));
    if (chunkText) {
      chunks.push({
        text: chunkText,
        start: Math.max(0, start),
        end: Math.max(start + 0.35, end)
      });
    }
  }

  return chunks;
}

/**
 * Parses WebVTT subtitle text generated by edge-tts into timed segments
 * @param {string} vttContent
 * @returns {Array<{ startSec: number, endSec: number, text: string }>}
 */
export function parseVttTiming(vttContent) {
  if (!vttContent) return [];
  const lines = vttContent.split(/\r?\n/);
  const segments = [];
  const timeRegex = /(\d{2}):(\d{2}):(\d{2})[.,](\d{3})\s*-->\s*(\d{2}):(\d{2}):(\d{2})[.,](\d{3})/;

  for (let i = 0; i < lines.length; i++) {
    const match = lines[i].match(timeRegex);
    if (match) {
      const startSec = parseInt(match[1], 10) * 3600 + parseInt(match[2], 10) * 60 + parseInt(match[3], 10) + parseInt(match[4], 10) / 1000;
      const endSec = parseInt(match[5], 10) * 3600 + parseInt(match[6], 10) * 60 + parseInt(match[7], 10) + parseInt(match[8], 10) / 1000;
      let text = '';
      let j = i + 1;
      while (j < lines.length && lines[j].trim() !== '' && !lines[j].match(/^\d+$/) && !lines[j].includes('-->')) {
        text += (text ? ' ' : '') + lines[j].trim();
        j++;
      }
      const clean = cleanCaptionText(text);
      if (clean && endSec > startSec) {
        segments.push({ startSec, endSec, text: clean });
      }
    }
  }
  return segments;
}

/**
 * Generates timed caption chunks from an array of pre-timed segments (from VTT).
 * This eliminates proportional drift and locks captions to actual neural speech.
 */
export function generateCaptionsFromTimedSegments(timedSegments = [], aspectRatio = '9:16') {
  if (!timedSegments || timedSegments.length === 0) return [];
  const wordsPerChunk = aspectRatio === '9:16' ? 3 : 5;
  const allChunks = [];

  for (const seg of timedSegments) {
    const dur = Math.max(0.3, seg.endSec - seg.startSec);
    const chunks = chunkSentenceForCaptions(seg.text, dur, seg.startSec, wordsPerChunk);
    allChunks.push(...chunks);
  }

  return allChunks;
}

/**
 * Generates timed caption chunks from an array of clauses,
 * ensuring each clause's captions are tightly locked to when that clause is spoken.
 * If timedSegments are provided from TTS, uses real speech boundaries.
 *
 * @param {string[]} clauses - Array of narration sentences
 * @param {number} totalDurationSec - Total audio duration
 * @param {'9:16'|'16:9'} [aspectRatio='9:16']
 * @param {Array<{ startSec: number, endSec: number, text: string }>} [timedSegments=null]
 * @returns {Array<{ text: string, start: number, end: number }>}
 */
export function generateCaptionsFromClauses(clauses, totalDurationSec, aspectRatio = '9:16', timedSegments = null) {
  if (timedSegments && timedSegments.length > 0) {
    return generateCaptionsFromTimedSegments(timedSegments, aspectRatio);
  }

  const validClauses = (clauses || []).map(c => cleanCaptionText(c)).filter(Boolean);
  if (validClauses.length === 0) return [];

  const totalWords = validClauses.reduce((sum, c) => sum + c.split(/\s+/).length, 0);
  if (totalWords === 0) return [];

  const wordsPerChunk = aspectRatio === '9:16' ? 3 : 5;
  const allChunks = [];
  let currentTimeOffset = 0;

  for (const clause of validClauses) {
    const wordCount = clause.split(/\s+/).length;
    const clauseDuration = totalDurationSec * (wordCount / totalWords);
    const chunks = chunkSentenceForCaptions(clause, clauseDuration, currentTimeOffset, wordsPerChunk);
    allChunks.push(...chunks);
    currentTimeOffset += clauseDuration;
  }

  return allChunks;
}

