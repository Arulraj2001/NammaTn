/**
 * Returns a topic by ID or rotating by schedule
 * @param {number} dayOfWeek - 0 (Sun) to 6 (Sat)
 * @param {string} [requestedSeriesId] - Optional series filter
 * @param {number} [episodeOffset=0] - Offset for rotation
 */
export function getPodcastTopicForSchedule(dayOfWeek = new Date().getDay(), requestedSeriesId = null, episodeOffset = 0) {
  let targetSeries = requestedSeriesId;

  if (!targetSeries) {
    if (dayOfWeek === 2) targetSeries = 'scam-files';         // Tuesday
    else if (dayOfWeek === 4) targetSeries = 'citizen-playbook'; // Thursday
    else if (dayOfWeek === 6) targetSeries = 'hidden-tn';       // Saturday
    else {
      // Default to rotating based on day of year
      const dayOfYear = Math.floor((new Date() - new Date(new Date().getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
      const seriesList = ['scam-files', 'citizen-playbook', 'hidden-tn'];
      targetSeries = seriesList[dayOfYear % 3];
    }
  }

  const seriesTopics = PODCAST_CATALOG.filter(t => t.seriesId === targetSeries);
  if (seriesTopics.length === 0) return PODCAST_CATALOG[0];

  const dayOfYear = Math.floor((new Date() - new Date(new Date().getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
  const selectedIndex = (dayOfYear + episodeOffset) % seriesTopics.length;
  return seriesTopics[selectedIndex];
}
