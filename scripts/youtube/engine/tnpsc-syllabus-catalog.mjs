export function getMasterclassTopicForDay(dayNumber) {
  return TNPSC_UNIT8_CATALOG.find(t => t.dayNumber === dayNumber) || TNPSC_UNIT8_CATALOG[0];
}

export function getTodayMasterclassTopic(date = null) {
  const d = date ? new Date(date) : new Date();
  const dayOfYear = Math.floor((d - new Date(d.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
  const index = dayOfYear % TNPSC_UNIT8_CATALOG.length;
  return TNPSC_UNIT8_CATALOG[index];
}
